import {readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const snapshotPath = path.join(repositoryRoot, 'demos/SNAPSHOT.json');
const outputPath = path.join(repositoryRoot, 'demos/registry.generated.ts');
const snapshot = JSON.parse(await readFile(snapshotPath, 'utf8'));
const publicIds = Object.entries(snapshot.sources)
  .filter(([, source]) =>
    source.public === true &&
    source.publication?.access === 'public-preview' &&
    source.publication?.rightsApproval === 'approved'
  )
  .map(([id]) => id)
  .sort();

for (const id of publicIds) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(id)) {
    throw new Error(`Unsafe public demo id: ${id}`);
  }
  await readFile(path.join(repositoryRoot, 'demos/modules', `${id}.tsx`), 'utf8');
}

const loaders = publicIds
  .map(
    (id) =>
      `  '${id}': () => import('./modules/${id}').then(({default: animationModule}) => animationModule)`,
  )
  .join(',\n');
const generated = `/* This file is generated by scripts/generate-registry.mjs. Do not edit. */
import type {AnimationModule} from './contract';

export type AnimationModuleLoader = () => Promise<AnimationModule>;

export const animationModuleLoaders: Readonly<Record<string, AnimationModuleLoader>> = Object.freeze({
${loaders}
});
`;

await writeFile(outputPath, generated, 'utf8');
